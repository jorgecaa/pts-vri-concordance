def sd(t):
    for k,v in {'ā':'a','ī':'i','ū':'u','ṁ':'m','ṃ':'m','ṅ':'n','ñ':'n','ṭ':'t','ḍ':'d','ṇ':'n','ḷ':'l'}.items():
        t=t.replace(k,v).replace(k.upper(),v.upper())
    return t

ok = issues = 0
for num, book, page in MN_DATA:
    cur.execute('SELECT head, unitext FROM pages WHERE book_no=? AND page_no=? AND edition="mula"', (book, page))
    r = cur.fetchone()
    if not r: issues+=1; continue
    
    head = r['head'] or ''
    ns = str(num)
    
    # Has sutta number in head? e.g. "(14)" or "(14.)"
    if f'({ns})' in head or f'({ns}.)' in head:
        ok += 1; continue
    
    # Has 'evam me sutam' in body text?
    txt = (r['unitext'] or '').lower()
    if 'evam me sutam' in txt or 'evaṃ me sutaṃ' in txt:
        ok += 1; continue
    
    # Check next page head
    cur.execute('SELECT head FROM pages WHERE book_no=? AND page_no=? AND edition="mula"', (book, page+1))
    r2 = cur.fetchone()
    if r2 and (f'({ns})' in (r2['head'] or '') or f'({ns}.)' in (r2['head'] or '')):
        ok += 1; continue
    
    # Check prev page head
    cur.execute('SELECT head FROM pages WHERE book_no=? AND page_no=? AND edition="mula"', (book, page-1))
    r3 = cur.fetchone()
    if r3 and (f'({ns})' in (r3['head'] or '') or f'({ns}.)' in (r3['head'] or '')):
        print(f'  ⚠ MN {num:>3d} p.{page}: found on p.{page-1}')
        issues += 1; continue
    
    print(f'  ⚠ MN {num:>3d} p.{page}: NOT VERIFIED head=[{head[:50].strip()}]')
    issues += 1

print(f'\n✓ OK: {ok}/152  ⚠ Issues: {issues}/152')
